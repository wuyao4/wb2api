import { createHash, randomBytes, randomUUID } from 'node:crypto';
import { HttpError } from '../../core/errors.js';
import { log, warn } from '../../core/logger.js';
import { OAuthProvider, PollScheduler, authError } from './base.js';

/**
 * Qoder — PKCE device-code flow.
 *
 * Qoder's desktop client redirects to the custom scheme `qoder-app://`, which a
 * Node process cannot receive. The official CLI therefore uses a different
 * branch, and that is the one implemented here:
 *
 *   1. open  {authBase}/device/selectAccounts?challenge&challenge_method&nonce&machine_id&client_id
 *   2. poll  {openApiBase}/api/v1/deviceToken/poll?nonce&verifier&challenge_method
 *
 * Verified live: the auth page answers 200 and the poll endpoint answers 404
 * `{"errorCode":"NotFound"}` for an unknown session — which is the documented
 * "not approved yet" signal, not a failure. Any other unknown path on that host
 * answers 401, which is how the 404 reading is confirmed.
 *
 * Two things matter for correctness:
 *   - `client_id` must be the production one. The non-prod id is rejected at the
 *     callback stage with a misleading "invalid parameter" page.
 *   - `machine_id` is generated by us and persisted; it participates in the
 *     server's device binding and is required by refresh.
 */

const AUTH_BASE = 'https://qoder.com';
const OPENAPI_BASE = 'https://openapi.qoder.sh';
/** Production client id (the non-prod one is rejected at callback). */
const CLIENT_ID = 'e883ade2-e6e3-4d6d-adf7-f92ceff5fdcb';

const SELECT_PATH = '/device/selectAccounts';
const POLL_PATH = '/api/v1/deviceToken/poll';
const REFRESH_PATH = '/api/v1/deviceToken/refresh';
const USERINFO_PATH = '/api/v1/userinfo';

const PKCE_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~';

function makePkce() {
  const length = 43 + Math.floor(86 * Math.random());
  const bytes = randomBytes(length);
  let verifier = '';
  for (let i = 0; i < length; i += 1) verifier += PKCE_ALPHABET[bytes[i] % PKCE_ALPHABET.length];
  const challenge = createHash('sha256')
    .update(verifier)
    .digest('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
  return { verifier, challenge };
}

export class QoderOAuth extends OAuthProvider {
  constructor({ persist }) {
    super({ id: 'qoder', name: 'Qoder', kind: 'device-code', persist });
  }

  async start({ channelId = 'qoder' } = {}) {
    this.prune();

    const pkce = makePkce();
    const nonce = randomUUID();
    const machineId = randomUUID();
    const state = randomUUID().replace(/-/g, '');

    const authUrl = `${AUTH_BASE}${SELECT_PATH}?${new URLSearchParams({
      challenge: pkce.challenge,
      challenge_method: 'S256',
      nonce,
      machine_id: machineId,
      client_id: CLIENT_ID
    }).toString()}`;

    const session = {
      at: Date.now(),
      status: 'pending',
      channelId,
      nonce,
      verifier: pkce.verifier,
      machineId,
      expiresAt: new Date(Date.now() + 5 * 60 * 1000).toISOString(),
      controller: new AbortController()
    };
    this.sessions.set(state, session);
    this.#pollInBackground(state, session);

    return {
      state,
      authUrl,
      mode: 'device-code',
      channelId,
      expiresAt: session.expiresAt,
      note: '在浏览器完成 Qoder 登录授权；本页会自动继续。'
    };
  }

  async #pollInBackground(state, session) {
    const scheduler = new PollScheduler(1000, { minMs: 1000, stepMs: 1000, maxMs: 10000 });
    const deadline = Date.now() + 5 * 60 * 1000;
    let failures = 0;

    const pollUrl = `${OPENAPI_BASE}${POLL_PATH}?${new URLSearchParams({
      nonce: session.nonce,
      verifier: session.verifier,
      challenge_method: 'S256'
    }).toString()}`;

    try {
      while (Date.now() < deadline) {
        await scheduler.sleep(session.controller.signal);

        let res;
        let payload = null;
        try {
          res = await fetch(pollUrl, {
            headers: { Accept: 'application/json' },
            signal: session.controller.signal
          });
          failures = 0;
        } catch (error) {
          if (session.controller.signal.aborted) return;
          failures += 1;
          if (failures >= 5) {
            throw authError(`无法连接 Qoder 登录服务（连续 ${failures} 次失败）：${error.message}`);
          }
          continue;
        }

        // 404 = session not approved yet (verified: other unknown paths 401).
        if (res.status === 404) continue;

        if (!res.ok) {
          throw authError(`Qoder 授权轮询失败（HTTP ${res.status}）`);
        }

        payload = await res.json().catch(() => null);
        const accessToken = String(payload?.access_token || payload?.accessToken || '');
        if (!accessToken) continue;

        session.status = 'success';
        session.credential = {
          accessToken,
          securityOauthToken: String(payload.security_oauth_token || accessToken),
          refreshToken: String(payload.refresh_token || payload.refreshToken || ''),
          expiresAt: readTimestamp(payload.expire_time || payload.expires_at),
          refreshExpiresAt: readTimestamp(
            payload.refresh_token_expire_time || payload.refresh_token_expires_at
          ),
          machineId: session.machineId,
          userId: String(payload.user_id || payload.uid || ''),
          nickname: String(payload.user_name || payload.nickname || '')
        };
        session.account = {
          label: session.credential.nickname || session.credential.userId || 'Qoder',
          username: session.credential.nickname || session.credential.userId
        };
        log('[qoder] authorization completed');
        return;
      }
      throw authError('Qoder 授权超时，请重新发起');
    } catch (error) {
      if (session.status === 'success') return;
      if (session.controller.signal.aborted) return;
      session.status = 'error';
      session.error = error.message;
      warn(`[qoder] authorization failed: ${error.message}`);
    }
  }

  poll(state) {
    return this.takeResult(state);
  }

  /** Refresh an access token using the stored refresh token + machine id. */
  async refresh(credential) {
    if (!credential?.refreshToken) throw new HttpError(400, '该账号没有刷新令牌');
    const res = await fetch(`${OPENAPI_BASE}${REFRESH_PATH}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify({
        refresh_token: credential.refreshToken,
        machine_id: credential.machineId
      }),
      signal: AbortSignal.timeout(30000)
    });
    const payload = await res.json().catch(() => null);
    if (!res.ok) {
      throw authError(`Qoder 续期失败（HTTP ${res.status}）`);
    }
    const accessToken = String(payload?.access_token || payload?.accessToken || '');
    if (!accessToken) throw authError('Qoder 续期响应缺少访问令牌');
    return {
      ...credential,
      accessToken,
      securityOauthToken: String(payload.security_oauth_token || accessToken),
      refreshToken: String(payload.refresh_token || credential.refreshToken),
      expiresAt: readTimestamp(payload.expire_time || payload.expires_at)
    };
  }
}

function readTimestamp(value) {
  if (typeof value === 'number' && Number.isFinite(value) && value > 0) {
    return value < 1e12 ? Math.round(value * 1000) : Math.round(value);
  }
  if (typeof value === 'string' && value) {
    const parsed = Date.parse(value);
    if (!Number.isNaN(parsed)) return parsed;
    const numeric = Number(value);
    if (Number.isFinite(numeric) && numeric > 0) {
      return numeric < 1e12 ? Math.round(numeric * 1000) : Math.round(numeric);
    }
  }
  return 0;
}

export { OPENAPI_BASE as QODER_OPENAPI_BASE, USERINFO_PATH as QODER_USERINFO_PATH };
